"""
Strategy Backtest Skill — 策略回测技能。

告诉 LLM 如何设计、执行和分析量化策略回测。
"""
from ..models import Skill

STRATEGY_BACKTEST_SKILL = Skill(
    name="strategy_backtest",
    description="设计并执行量化交易策略回测，包括策略参数设定、回测执行和结果分析",
    keywords=["回测", "策略", "量化", "均线策略", "交易策略", "收益", "胜率"],
    routes=["strategy", "backtest"],
    content="""# 策略回测技能

当用户想要测试某个交易策略的历史表现时，按以下流程执行：

## 回测流程

### 第一步：明确策略定义
确认用户想要测试的策略类型：
- **均线交叉策略**：短期均线上穿长期均线买入，下穿卖出
- **动量策略**：过去 N 日涨幅排名靠前的股票
- **均值回归策略**：价格偏离均值超过阈值时反向操作
- **用户自定义策略**：根据用户描述构建策略

### 第二步：设定回测参数
- **回测区间**：默认最近 1 年，可调整
- **初始资金**：默认 100 万元
- **交易成本**：手续费 0.03% + 印花税 0.1%
- **滑点**：默认 0.1%
- **基准指数**：沪深300

### 第三步：执行回测
1. 获取回测区间内的日K线数据
2. 按策略规则模拟每日交易决策
3. 记录每次交易的买入/卖出价格、时间、收益
4. 计算持仓市值和可用资金的每日变化

### 第四步：分析回测结果
输出以下指标：
- **总收益率** 和 **年化收益率**
- **最大回撤** 及发生时间
- **夏普比率**
- **胜率**（盈利交易次数 / 总交易次数）
- **盈亏比**（平均盈利 / 平均亏损）
- **交易次数** 和 **换手率**
- **相对基准的超额收益**

### 第五步：给出评价
- 策略是否有效
- 主要风险点
- 参数敏感性说明
- 改进建议

## 注意事项
- 回测结果不代表未来收益
- 需要说明过拟合风险
- 对于参数优化，应测试多组参数而非单点
""",
    version="1.0",
)
