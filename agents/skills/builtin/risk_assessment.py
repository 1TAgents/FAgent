"""
Risk Assessment Skill — 风险评估技能。

告诉 LLM 如何按专业流程完成投资组合风险评估。
"""
from ..models import Skill

RISK_ASSESSMENT_SKILL = Skill(
    name="risk_assessment",
    description="评估股票或投资组合的风险水平，包括波动率、最大回撤、Beta值等风险指标",
    keywords=["风险", "波动", "回撤", "Beta", "夏普", "风险评估", "风控"],
    routes=["strategy", "chat"],
    content="""# 风险评估技能

当用户询问某只股票或投资组合的风险、波动性、安全性时，按以下流程执行：

## 分析流程

### 第一步：获取历史数据
1. 使用 get_kline 获取至少 120 日的日K线数据
2. 提取每日收盘价计算收益率序列

### 第二步：计算风险指标
- **年化波动率**：日收益率标准差 × √252
- **最大回撤**：历史最高点到最低点的最大跌幅
- **夏普比率**：(年化收益率 - 无风险利率) / 年化波动率
- **Beta系数**：相对于基准指数（沪深300）的敏感度
- **VaR (Value at Risk)**：95% 置信度下的日最大亏损

### 第三步：风险评级
根据综合评分将风险分为 5 级：
1. **低风险**：波动率 < 15%，最大回撤 < 10%，夏普 > 1.0
2. **中低风险**：波动率 15-25%，最大回撤 10-20%
3. **中等风险**：波动率 25-35%，最大回撤 20-30%
4. **中高风险**：波动率 35-50%，最大回撤 30-50%
5. **高风险**：波动率 > 50%，最大回撤 > 50%

### 第四步：输出报告
- 各风险指标数值
- 综合风险评级
- 风险来源分析
- 降低风险的建议

## 注意事项
- 历史数据不代表未来表现
- 需要明确说明计算方法和假设
- 对于新股或数据不足的标的，应标注结果可靠性较低
""",
    version="1.0",
)
